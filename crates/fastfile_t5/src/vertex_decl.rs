//! BO1 vertex declarations: for each of the 18 source layouts, which stream,
//! byte offset and format code feeds each of ten element slots, and which
//! destination usage each slot name maps to.

/// One element of a source layout: stream, byte offset, format code.
type Element = [u8; 3];

/// Slot with nothing in it: stream 255.
const UNUSED: Element = [255, 0, 0];

/// A layout from its occupied slots only.
const fn layout(used: &[(usize, Element)]) -> [Element; 10] {
    let mut slots = [UNUSED; 10];
    let mut i = 0;
    while i < used.len() {
        slots[used[i].0] = used[i].1;
        i += 1;
    }
    slots
}

